"""Extract English -> katakana readings from the pinned bundled azooKey dictionary.

Only public standard dictionary shards are read; no user dictionaries or history.
Usage: python3 Tools/generate_latin_readings.py /path/to/azooKey_dictionary_storage
"""
import argparse
import json
from pathlib import Path
import re
import shutil
import struct


def extract(root):
    entries = {}
    paths = sorted((root / 'Dictionary/louds').glob('*.loudstxt3'))
    if not paths:
        raise ValueError('No standard dictionary shards found')
    for path in paths:
        data = path.read_bytes()
        count = struct.unpack_from('<H', data)[0]
        offsets = list(struct.unpack_from('<' + str(count) + 'I', data, 2)) + [len(data)]
        if offsets != sorted(offsets) or offsets[0] < 2 + 4 * count:
            raise ValueError(f'Invalid offsets: {path}')
        for start, end in zip(offsets, offsets[1:]):
            rows = struct.unpack_from('<H', data, start)[0]
            if not rows:
                continue
            fields = data[start + 2 + 10 * rows:end].decode('utf-8').split('\t')
            if len(fields) != rows + 1:
                raise ValueError(f'Invalid text rows: {path}')
            ruby = fields[0]
            if not re.fullmatch('[ァ-ヶー]+', ruby):
                continue
            for word in fields[1:]:
                if re.fullmatch("[A-Za-z][A-Za-z0-9'-]*", word):
                    entries.setdefault(word.lower(), set()).add(ruby)
    return {word: sorted(readings) for word, readings in sorted(entries.items())}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('dictionary', type=Path)
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / 'Core/Sources/Core/Resources'
    output.mkdir(parents=True, exist_ok=True)
    entries = extract(args.dictionary)
    (output / 'LatinReadings.json').write_text(json.dumps(entries, ensure_ascii=False, indent=2) + '\n')
    shutil.copyfile(args.dictionary / 'LICENSE', output / 'LatinReadings-LICENSE.txt')
    (output / 'LatinReadings-NOTICE.txt').write_text(
        'LatinReadings.json is a modified, reverse-indexed subset of azooKey_dictionary_storage.\n'
        'Copyright 2024 Miwa / ensan. Licensed under Apache License 2.0.\n'
        'Source: https://github.com/azooKey/azooKey_dictionary_storage\n'
        'Extracted from AzooKeyKanaKanjiConverter revision ad714fea8cb2fe113aea86ba5c42563cdaf77cfb.\n'
        'Generated by Tools/generate_latin_readings.py; only ASCII words with katakana readings retained.\n')
    print(f'Generated {len(entries)} English reading entries')
